/** How the target will be cleaned, in words the user can check against their own shell. */
export function cacheMethodLabel(target: CacheTarget): string {
  switch (target.cleanup.type) {
    case 'external_command':
      return target.cleanup.display;
    case 'truncate_file':
      return 'empty in place';
    default:
      return 'delete';
  }
}

/** Handed to the tool's own prune: what it frees is known only once it has run. */
export function isPruneTarget(target: { cleanup: { type: string } }): boolean {
  return target.cleanup.type === 'external_command';
}

/** `~/…` for paths under the home folder, which is how people read them. */
export function shortenHome(path: string): string {
  return path.replace(/^\/Users\/[^/]+(?=\/|$)/, '~').replace(/^\/home\/[^/]+(?=\/|$)/, '~');
}

/** The path below the scanned folder, so rows named `api` or `web` can be told apart. */
export function relativeTo(path: string, root: string | null): string {
  if (!root) return shortenHome(path);
  const base = root.replace(/[/\\]+$/, '');
  if (path.startsWith(`${base}/`) || path.startsWith(`${base}\\`)) {
    return path.slice(base.length + 1);
  }
  return shortenHome(path);
}

export function formatAgeShort(lastModified: number | null, nowSeconds = Date.now() / 1000): string {
  if (lastModified === null) return '';
  const days = Math.floor((nowSeconds - lastModified) / 86_400);
  if (days < 1) return 'today';
  if (days < 30) return `${days} d`;
  if (days < 365) return `${Math.floor(days / 30)} mo`;
  return `${Math.floor(days / 365)} y`;
}
