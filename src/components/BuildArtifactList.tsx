import type { ArtifactKind, BuildArtifact } from '../types';
import { formatSize } from '../utils/formatSize';
import { SizeDisplay } from './SizeDisplay';

/** Display order, label and — the part that matters — what deleting each kind costs. */
const KINDS: Array<{ kind: ArtifactKind; label: string; folder: string; cost: string }> = [
  {
    kind: 'cargo_target',
    label: 'Rust (Cargo)',
    folder: 'target',
    cost: 'What cargo clean removes. The next build compiles from scratch; release binaries, app bundles, docs and benchmark baselines kept only here go too.',
  },
  {
    kind: 'cocoapods',
    label: 'CocoaPods',
    folder: 'Pods',
    cost: 'Restored by pod install (needs network); the next iOS build also recompiles every pod.',
  },
  {
    kind: 'next_build',
    label: 'Next.js',
    folder: '.next',
    cost: 'Build output and cache, rebuilt by next build or next dev.',
  },
  {
    kind: 'nx_cache',
    label: 'Nx',
    folder: '.nx',
    cost: 'Local task cache and workspace data, recomputed on the next run.',
  },
  {
    kind: 'turbo_cache',
    label: 'Turborepo',
    folder: '.turbo',
    cost: 'Local task cache and run logs.',
  },
  {
    kind: 'android_cxx',
    label: 'Android native (CMake)',
    folder: '.cxx',
    cost: 'Native build intermediates, rebuilt by Gradle.',
  },
  {
    kind: 'coverage',
    label: 'Test coverage',
    folder: 'coverage',
    cost: 'Coverage reports, regenerated by the next test run with coverage.',
  },
  {
    kind: 'expo_state',
    label: 'Expo',
    folder: '.expo',
    cost: 'Expo CLI local state, recreated by expo start.',
  },
];

interface BuildArtifactListProps {
  artifacts: BuildArtifact[];
  selectedPaths: Set<string>;
  onToggleSelection: (path: string) => void;
  onSetKindSelected: (kind: ArtifactKind, selected: boolean) => void;
  onDeselectAll: () => void;
  selectionDisabled?: boolean;
}

function formatAge(lastModified: number | null): string | null {
  if (lastModified === null) return null;
  const days = Math.floor((Date.now() / 1000 - lastModified) / 86_400);
  if (days < 1) return 'changed today';
  return `changed ${days} day${days === 1 ? '' : 's'} ago`;
}

function setIndeterminate(input: HTMLInputElement | null, some: boolean, all: boolean) {
  if (input) input.indeterminate = some && !all;
}

export function BuildArtifactList({
  artifacts,
  selectedPaths,
  onToggleSelection,
  onSetKindSelected,
  onDeselectAll,
  selectionDisabled = false,
}: BuildArtifactListProps) {
  const groups = KINDS
    .map((meta) => ({ ...meta, items: artifacts.filter((artifact) => artifact.kind === meta.kind) }))
    .filter((group) => group.items.length > 0);
  const selectedCount = artifacts.filter((artifact) => selectedPaths.has(artifact.path)).length;

  return (
    <div className="flex flex-col">
      <div className="flex items-center justify-between gap-4 py-3 px-4 bg-orange-50/70 border-b border-orange-100">
        <div className="flex items-center gap-2">
          <h2 className="font-medium text-gray-800">Build folders</h2>
          <span className="text-xs text-gray-500">
            ({selectedCount} of {artifacts.length} selected)
          </span>
        </div>
        <button
          type="button"
          onClick={onDeselectAll}
          disabled={selectionDisabled || selectedCount === 0}
          className="text-xs text-orange-700 hover:text-orange-900 disabled:opacity-40 disabled:cursor-not-allowed"
        >
          Deselect All
        </button>
      </div>

      <p className="px-4 py-2 text-xs text-gray-500 border-b border-gray-100">
        Offered only where the tool that made the folder left its marks beside and inside it, and
        never when Git tracks anything inside. Select each kind on its own: what a delete costs
        differs a lot between them.
      </p>

      {groups.length === 0 ? (
        <div className="min-h-24 flex items-center justify-center text-gray-500 text-sm">
          No build folders found
        </div>
      ) : (
        groups.map((group) => {
          const groupSelected = group.items.filter((item) => selectedPaths.has(item.path)).length;
          const allSelected = groupSelected === group.items.length;
          const total = group.items.reduce((sum, item) => sum + item.reclaimable_size, 0);
          return (
            <section key={group.kind} className="border-b border-gray-100 last:border-b-0">
              <label className="flex items-start gap-3 px-4 py-2 bg-gray-50 cursor-pointer">
                <input
                  type="checkbox"
                  aria-label={`Select all ${group.label} folders`}
                  disabled={selectionDisabled}
                  checked={allSelected}
                  ref={(input) => setIndeterminate(input, groupSelected > 0, allSelected)}
                  onChange={() => onSetKindSelected(group.kind, !allSelected)}
                  className="mt-0.5 w-4 h-4 rounded border-gray-300 text-orange-600 focus:ring-orange-500 disabled:opacity-40"
                />
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-2 text-sm">
                    <span className="font-medium text-gray-800">{group.label}</span>
                    <code className="text-xs text-gray-500">{group.folder}</code>
                    <span className="text-xs text-gray-500">
                      · {group.items.length} · {formatSize(total)}
                    </span>
                  </div>
                  <p className="text-[11px] text-gray-500">{group.cost}</p>
                </div>
              </label>
              <ul className="divide-y divide-gray-100">
                {group.items.map((artifact) => {
                  const age = formatAge(artifact.last_modified);
                  return (
                    <li key={artifact.path}>
                      <label
                        className={`
                        flex items-center gap-4 pl-11 pr-4 py-2.5 transition-colors
                        ${selectionDisabled ? 'cursor-not-allowed opacity-70' : 'hover:bg-gray-50 cursor-pointer'}
                        ${selectedPaths.has(artifact.path) ? 'bg-orange-50' : ''}
                      `}
                      >
                        <input
                          type="checkbox"
                          aria-label={`Select ${group.folder} in ${artifact.parent_project}`}
                          disabled={selectionDisabled}
                          checked={selectedPaths.has(artifact.path)}
                          onChange={() => onToggleSelection(artifact.path)}
                          className="w-4 h-4 rounded border-gray-300 text-orange-600 focus:ring-orange-500 disabled:opacity-40"
                        />
                        <div className="flex-1 min-w-0">
                          <div className="flex items-center gap-2">
                            <span className="font-medium text-gray-900">{artifact.parent_project}</span>
                            {age && <span className="text-[10px] text-gray-400">{age}</span>}
                          </div>
                          <p className="text-xs text-gray-400 truncate" title={artifact.path}>
                            {artifact.path}
                          </p>
                        </div>
                        <SizeDisplay bytes={artifact.reclaimable_size} className="whitespace-nowrap" />
                      </label>
                    </li>
                  );
                })}
              </ul>
            </section>
          );
        })
      )}
    </div>
  );
}
